# --- where each picture goes -------------------------------------------------

def published(rel):
    """A path that survives being published: no directory starts with a dot.

    GitHub's Pages upload leaves out `.github`, so `ci.yml`'s picture would be
    written and never served under its own name.
    """
    return "/".join(("dot-" + part[1:]) if part.startswith(".") else part
                    for part in rel.split("/"))


def file_picture(rel):
    return "files/%s.svg" % published(rel)


def crate_picture(crate):
    return "crates/%s.svg" % crate


def index_page(models, crate_models, history):
    """The folder's README: every crate drawn, every file linked."""
    out = [
        "<!-- SPDX-License-Identifier: GPL-3.0-or-later -->",
        "<!-- %s from %s, ROADMAP.md and docs/AUDIT.md." % (MARKER, HISTORY),
        "     Do not edit: run the generator. CI verifies it with",
        "         python tools/graphs/generate.py --check",
        "-->",
        "",
        "# Every crate and every file, over time",
        "",
        "One picture per crate and one per source file. Each says what the "
        "file is for, in its own words, and then its life: a row for each "
        "release that changed it, a row for what has landed since the last "
        "release, and a row for what the roadmap has ahead for it.",
        "",
        "| Square | Means |",
        "|---|---|",
    ]
    for name, _, _, note in STATES:
        out.append("| **%s** | %s |" % (name, note))
    out += [
        "",
        "Point at a square to read the change or the roadmap item it stands "
        "for. GitHub shows a picture as an image, which has no hover, so "
        "open one from the website, or open the file itself, to read them. "
        "One square is one change, not one size of change.",
        "",
        "The changes come from the commit history, recorded through %s by "
        "`python tools/graphs/generate.py --record`. What is ahead comes from "
        "[`ROADMAP.md`](../../ROADMAP.md), and a planned item is a patch when a "
        "finding in [`docs/AUDIT.md`](../../docs/AUDIT.md) ties it to the file."
        % long_day(history["through"]),
        "",
        "## Crates",
        "",
    ]
    for crate, model in crate_models:
        out.append("### %s" % crate)
        out.append("")
        out.append("![%s](%s)" % (crate, crate_picture(crate)))
        out.append("")
    out += ["## Files", ""]
    current = None
    for rel, model in models:
        folder = rel.rsplit("/", 1)[0] if "/" in rel else "(top level)"
        if folder != current:
            if current is not None:
                out.append("")
            out.append("### %s" % folder)
            out.append("")
            current = folder
        name = rel.rsplit("/", 1)[-1]
        line = "- [`%s`](%s)" % (name, file_picture(rel))
        if model["what"]:
            line += ": %s" % model["what"]
        out.append(line)
    out.append("")
    return "\n".join(out)


def build(root, history=None):
    colours = docs.palette(root)
    history = history or load_history(root)
    files = source_files(root)
    per_file, per_crate, rows = ahead(root, files, history)

    touching = {rel: [] for rel in files}
    for commit in history["commits"]:
        for rel in commit["files"]:
            if rel in touching:
                touching[rel].append(commit)

    outputs = {}
    models = []
    for rel in files:
        what = describe(rel, docs.read(os.path.join(root, rel)))
        picture = drawing(colours, rel, what, history, touching[rel],
                          per_file[rel], rows, "file")
        for place in PLACES:
            outputs["%s/%s" % (place, file_picture(rel))] = picture
        models.append((rel, {"what": what}))

    crate_models = []
    for crate, members in crates_of(files):
        seen = set()
        commits = []
        for commit in history["commits"]:
            if any(rel in members for rel in commit["files"]):
                key = id(commit)
                if key not in seen:
                    seen.add(key)
                    commits.append(commit)
        what = plainer(docs.crate_description(root, crate))
        picture = drawing(colours, crate, what, history, commits,
                          per_crate[crate], rows, "crate")
        for place in PLACES:
            outputs["%s/%s" % (place, crate_picture(crate))] = picture
        crate_models.append((crate, {"what": what}))

    outputs[INDEX] = index_page(models, crate_models, history)
    return outputs


def orphans(root, outputs):
    """Pictures on disk that nothing generates any more."""
    stale = []
    for place in PLACES:
        base = os.path.join(root, place)
        for directory, _, names in os.walk(base):
            for name in names:
                rel = os.path.relpath(os.path.join(directory, name), root)
                rel = rel.replace(os.sep, "/")
                if rel not in outputs:
                    stale.append(rel)
    return sorted(stale)


def write(root, outputs):
    for rel in orphans(root, outputs):
        os.remove(os.path.join(root, rel))
        print("  removed %s" % rel)
    for place in PLACES:
        for directory, _, _ in sorted(os.walk(os.path.join(root, place)),
                                      reverse=True):
            if not os.listdir(directory):
                os.rmdir(directory)
    changed = 0
    for rel, text in sorted(outputs.items()):
        path = os.path.join(root, rel.replace("/", os.sep))
        if os.path.exists(path) and docs.read(path) == text:
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with io.open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        changed += 1
    print("  %d graph file(s) written, %d current" % (changed, len(outputs)))


def check(root, outputs):
    stale = []
    for rel, text in sorted(outputs.items()):
        path = os.path.join(root, rel.replace("/", os.sep))
        if not os.path.exists(path) or docs.read(path) != text:
            stale.append(rel)
    extra = orphans(root, outputs)
    for rel in stale[:20]:
        print("  out of date: %s" % rel)
    if len(stale) > 20:
        print("  and %d more" % (len(stale) - 20))
    for rel in extra[:20]:
        print("  generated by nothing: %s" % rel)
    if stale or extra:
        print("\n  Run: python tools/graphs/generate.py")
        return 1
    print("every crate's and file's graph matches the tree and its history")
    return 0


