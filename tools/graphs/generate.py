def self_test():
    """Record a small history with a rename, a fix and a tag, and read it back."""
    failures = []

    def expect(condition, message):
        if not condition:
            failures.append(message)

    scratch = tempfile.mkdtemp(prefix="graphs-self-test-")
    try:
        environment = dict(os.environ, GIT_AUTHOR_NAME="test",
                           GIT_AUTHOR_EMAIL="test@example.invalid",
                           GIT_COMMITTER_NAME="test",
                           GIT_COMMITTER_EMAIL="test@example.invalid")

        clock = [0]

        def run(*args, day="2026-01-02"):
            # A different second for every commit, as real history has: the
            # release a change belongs to is matched partly by when it was
            # written.
            clock[0] += 1
            stamp = "%sT00:00:%02dZ" % (day, clock[0])
            environment["GIT_AUTHOR_DATE"] = environment["GIT_COMMITTER_DATE"] = stamp
            subprocess.run(["git"] + list(args), cwd=scratch, env=environment,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                           check=True)

        def put(name, text):
            with io.open(os.path.join(scratch, name), "w", encoding="utf-8") as h:
                h.write(text)

        run("init", "-q")
        run("config", "commit.gpgsign", "false")
        body = "".join("fn line_%d() {}\n" % n for n in range(40))
        put("old.rs", "//! Old.\n" + body)
        put("gone.rs", "//! A file that is deleted.\n")
        run("add", "-A")
        run("commit", "-q", "-m", "Roadmap 7 done: the first file")
        run("tag", "v0.1.0")
        run("mv", "old.rs", "new.rs")
        put("new.rs", "//! New.\n" + body + "fn one_more() {}\n")
        run("rm", "-q", "gone.rs")
        run("add", "-A")
        run("commit", "-q", "-m",
            "Renamed, and a fix — with a dash\n\n- docs/AUDIT.md: F-12")
        put("gone.rs", "//! The same name, a different file.\n")
        run("add", "-A")
        run("commit", "-q", "-m", "A new file under an old name")
        # A commit rebased on top keeps the older day it was written on.
        put("late.rs", "//! Written before, landed after.\n")
        run("add", "-A")
        run("commit", "-q", "-m", "Rebased onto the rest", day="2025-12-30")

        history = record(scratch, {"new.rs", "gone.rs", "late.rs"})
        expect(history["through"] == "2026-01-02",
               "history should be recorded through the newest day any commit "
               "carries, not HEAD's: got %s" % history["through"])
        by_file = {}
        for commit in history["commits"]:
            for rel in commit["files"]:
                by_file.setdefault(rel, []).append(commit)
        moved = by_file.get("new.rs", [])
        expect(len(moved) == 2,
               "a rename should carry the older history: new.rs has %d "
               "change(s), wants 2" % len(moved))
        if len(moved) == 2:
            expect(moved[0]["kind"] == "fix" and moved[0]["findings"] == [12],
                   "a commit naming F-12 should be a fix that names it")
            expect(moved[0]["release"] == "",
                   "a commit after the last tag should be unreleased")
            expect(moved[1]["release"] == "v0.1.0" and moved[1]["items"] == [7],
                   "the first commit should be in v0.1.0 and name item 7")
            expect("—" not in moved[0]["subject"],
                   "an em dash in a subject should not reach a picture")
        reused = by_file.get("gone.rs", [])
        expect(len(reused) == 1,
               "a file's history should start where it was created: gone.rs "
               "has %d change(s), wants 1" % len(reused))

        expect(describe("a.py", '"""Does a thing.\n\nMore."""\n') == "Does a thing.",
               "a Python docstring should give its first sentence")
        expect(describe("a.rs", "//! # crate\n//!\n//! Seals a file. Then more.\n")
               == "Seals a file.", "a Rust //! block should give its first sentence")
        expect(describe("a.sh", "#!/bin/sh\n# SPDX-License-Identifier: X\n"
                        "# Installs it.\nset -e\n") == "Installs it.",
               "a shell header should skip the shebang and the licence line")
        expect(describe("a.toml", "[package]\n") == "",
               "a file that says nothing should be described as nothing")
        expect(published(".github/workflows/ci.yml") == "dot-github/workflows/ci.yml",
               "a dot directory should be published under a name Pages serves")

        # Every line of text inside the canvas, as tools/site-tests/images.test.js
        # measures it, on a picture with a long title and a long description.
        colours = docs.palette(ROOT)
        rows = {9: {"number": 9, "status": "planned", "item": "**A plan**: detail"}}
        long_title = "crates/veilvoice-something/src/" + "x" * 70 + ".rs"
        svg = drawing(colours, long_title, "word " * 60, history, moved,
                      {9: "patch"}, rows, "file")
        width = float(re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg).group(1))
        height = float(re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg).group(2))
        for match in re.finditer(r'<text x="([\d.]+)" y="([\d.]+)"[^>]*'
                                 r'font-size="([\d.]+)"[^>]*>([^<]*)</text>', svg):
            x, y, size = (float(match.group(n)) for n in (1, 2, 3))
            text = re.sub(r"&[#\w]+;", "x", match.group(4))
            expect(x + len(text) * size * docs.TEXT_RATIO <= width + 1.5,
                   "text runs off the right edge: %r" % text[:40])
            expect(y + size * 0.28 <= height + 1.5,
                   "text runs off the bottom edge: %r" % text[:40])
        expect('stroke="var(--warn' in svg,
               "a planned patch should be drawn as an outline")
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    for message in failures:
        print("FAIL %s" % message)
    if failures:
        return 1
    print("the graph generator reads renames, fixes, releases and files correctly")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true",
                       help="fail if a graph is out of date or orphaned")
    group.add_argument("--record", action="store_true",
                       help="re-read the history from git, then write")
    group.add_argument("--self-test", action="store_true",
                       help="prove the history and the layout are read right")
    args = parser.parse_args()

    if args.self_test:
        return self_test()
    if args.record:
        history = record(ROOT, set(source_files(ROOT)))
        with io.open(os.path.join(ROOT, HISTORY), "w", encoding="utf-8",
                     newline="\n") as handle:
            handle.write(dump_history(history))
        print("  recorded %d commit(s) through %s into %s"
              % (len(history["commits"]), history["through"], HISTORY))
    outputs = build(ROOT)
    if args.check:
        return check(ROOT, outputs)
    write(ROOT, outputs)
    return 0


if __name__ == "__main__":
    sys.exit(main())
