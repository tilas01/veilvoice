# --- what a file says it does -----------------------------------------------

def plainer(text):
    """Text as a person reads it here: no em dash, single spaces."""
    text = text.replace(" — ", ", ").replace("—", ", ")
    return re.sub(r"\s+", " ", text).strip()


def hash_comment(text):
    """The `#` comment block a script or a config file opens with."""
    lines = []
    for raw in text.splitlines():
        stripped = raw.strip()
        if stripped.startswith("#!") and not lines:
            continue
        if stripped.startswith("#"):
            body = stripped.lstrip("#").strip()
            if body.startswith("SPDX-License-Identifier"):
                continue
            if not body and not lines:
                continue
            lines.append(body)
            continue
        if stripped.startswith("::") or stripped.lower().startswith("rem "):
            body = stripped[2:] if stripped.startswith("::") else stripped[4:]
            lines.append(body.strip())
            continue
        if not stripped and not lines:
            continue
        if stripped.lower() in ("@echo off",):
            continue
        break
    return lines


def xml_comment(text):
    """The first `<!-- -->` comment that is more than a licence line."""
    for match in re.finditer(r"<!--(.*?)-->", text[:6000], re.S):
        body = match.group(1).strip()
        body = re.sub(r"^SPDX-License-Identifier:\s*\S+\s*", "", body).strip()
        if body:
            return body.splitlines()
    match = re.search(r'<meta name="description" content="([^"]*)"', text)
    return [match.group(1)] if match else []


def describe(rel, text):
    """The first sentence the file says about itself, or "" if it says none."""
    name = rel.rsplit("/", 1)[-1]
    if name == "Cargo.toml":
        match = re.search(r'^description\s*=\s*"([^"]*)"', text, re.M)
        if match:
            return plainer(match.group(1))
    if name.endswith(".rs"):
        lines = docs.module_doc(text)
    elif name.endswith(".py"):
        try:
            lines = (ast.get_docstring(ast.parse(text)) or "").splitlines()
        except SyntaxError:
            lines = []
        if not lines:
            lines = hash_comment(text)
    elif name.endswith(".js"):
        lines = sources.header_comment(text, "js")
    elif name.endswith(".css"):
        lines = sources.header_comment(text, "css")
    elif name.endswith((".html", ".xml", ".wxs")):
        lines = xml_comment(text)
    else:
        lines = hash_comment(text)
    return plainer(docs.first_sentence(lines))


# --- recording the history ---------------------------------------------------

FINDING = re.compile(r"\bF-(\d+)\b")
ITEM = re.compile(r"\b[Rr]oadmap (?:item )?(\d+)\b")
FIX_TITLE = re.compile(r"^(?:fix|fixes|fixed)\b", re.I)
VERSION_TAG = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")


def git(root, *args):
    return subprocess.run(
        ["git", "-c", "core.quotePath=false"] + list(args), cwd=root,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        check=True).stdout.decode("utf-8", "replace")


def release_tags(root):
    tags = [t for t in git(root, "tag", "-l", "v*").split() if VERSION_TAG.match(t)]
    return sorted(tags, key=lambda t: tuple(int(n) for n in VERSION_TAG.match(t).groups()))


def classify(subject, body):
    """(kind, findings, items) for one commit message."""
    message = subject + "\n" + body
    findings = sorted({int(n) for n in FINDING.findall(message)})
    # Items from the title alone. A body names roadmap items in passing, for
    # context, and an audit round's names a dozen; a title names the one the
    # change is for.
    items = sorted({int(n) for n in ITEM.findall(subject)})
    kind = "fix" if findings or FIX_TITLE.match(subject) else "change"
    return kind, findings, items


def record(root, current):
    """Every commit that touched a file in `current`, newest first.

    `current` is the set of paths that exist now. The walk goes backwards in
    time and carries a map from the name a file had then to the name it has
    now, so a rename hands the older history to the new name. A file's history
    stops at the commit that created it: an older file that happened to have
    the same name is a different file.
    """
    if git(root, "rev-parse", "--is-shallow-repository").strip() == "true":
        raise SystemExit(
            "the history cannot be recorded from a shallow clone.\n"
            "  Run: git fetch --unshallow --tags origin")
    # Which release first carried each change, matched by when it was written
    # and what it was called rather than by hash. The branch this walks has
    # been rewritten once already, so the commits the tags point at are
    # copies of the ones on it, with the same dates and titles and different
    # hashes. A hash would tie every change to no release at all.
    tags = release_tags(root)
    release_of = {}
    written_at = {}
    released = {}
    for tag in tags:
        for line in git(root, "log", "--format=%at%x1f%s", tag).splitlines():
            stamp, _, subject = line.partition("\x1f")
            release_of.setdefault((stamp, subject), tag)
            written_at.setdefault(stamp, tag)
        released[tag] = git(root, "log", "-1", "--format=%cs", tag).strip()

    log = git(root, "log", "--no-merges", "--topo-order", "-M",
              "--name-status", "--format=%x1e%at%x1f%as%x1f%s%x1f%b%x1d",
              "HEAD")
    alias = {path: path for path in current}
    commits = []
    for chunk in log.split("\x1e")[1:]:
        head, _, changes = chunk.partition("\x1d")
        stamp, date, subject, body = head.split("\x1f", 3)
        release = release_of.get((stamp, subject), written_at.get(stamp, ""))
        touched = set()
        for line in changes.strip("\n").splitlines():
            parts = line.split("\t")
            if len(parts) < 2:
                continue
            status = parts[0]
            if status[:1] in ("R", "C") and len(parts) == 3:
                old, new = parts[1], parts[2]
                if new in alias:
                    touched.add(alias[new])
                    name = alias.pop(new)
                    if status[0] == "R":
                        alias[old] = name
            elif status == "A":
                if parts[1] in alias:
                    touched.add(alias.pop(parts[1]))
            elif status != "D" and parts[1] in alias:
                touched.add(alias[parts[1]])
        if not touched:
            continue
        subject = plainer(subject)
        kind, findings, items = classify(subject, body)
        commits.append({
            "date": date,
            "release": release,
            "kind": kind,
            "findings": findings,
            "items": items,
            "subject": subject,
            "files": sorted(touched),
        })
    # The newest day the walk saw, which is what "recorded through" means.
    # A rebase keeps each commit's own date, so HEAD's is not always the latest.
    through = max((c["date"] for c in commits),
                  default=git(root, "log", "-1", "--format=%as", "HEAD").strip())
    return {"through": through, "releases": released, "commits": commits}


def dump_history(history):
    """One commit per line, so a new recording is a readable diff."""
    out = ["{"]
    out.append('  "through": %s,' % json.dumps(history["through"]))
    out.append('  "releases": %s,' % json.dumps(history["releases"],
                                                 sort_keys=False))
    out.append('  "commits": [')
    rows = [json.dumps(commit, ensure_ascii=False, sort_keys=True)
            for commit in history["commits"]]
    out.append(",\n".join("    " + row for row in rows))
    out.append("  ]")
    out.append("}")
    return "\n".join(out) + "\n"


def load_history(root):
    path = os.path.join(root, HISTORY)
    if not os.path.exists(path):
        raise SystemExit(
            "%s does not exist.\n"
            "  Run, from a clone with the whole history:\n"
            "    python tools/graphs/generate.py --record" % HISTORY)
    with io.open(path, encoding="utf-8") as handle:
        return json.load(handle)


# --- what is ahead -----------------------------------------------------------

def mention(key):
    return re.compile(r"(?<![\w/.-])" + re.escape(key) + r"(?![\w/-])")


def keys_for(rel, files):
    """The ways a document can name this file and mean only this file."""
    keys = [rel]
    parts = rel.split("/")
    for start in range(1, len(parts)):
        suffix = "/".join(parts[start:])
        holders = [f for f in files if f == suffix or f.endswith("/" + suffix)]
        if holders == [rel] and suffix != rel:
            keys.append(suffix)
    return keys


def audit_sections(text):
    """docs/AUDIT.md cut at every `### ` heading, as text."""
    starts = [m.start() for m in re.finditer(r"^### ", text, re.M)]
    return [text[s:e] for s, e in zip(starts, starts[1:] + [len(text)])]


# What the roadmap calls two crates when it is not naming them. Its rows are
# written for people, so the desktop application is "the window" and the
# command-line program is "the command line", and a row about either almost
# never names the crate. Without these, the two crates most of the roadmap is
# about would show almost nothing ahead.
CRATE_PHRASES = {
    "veilvoice-gui": ("the window",),
    "veilvoice-cli": ("the command line",),
}


def ahead(root, files, history):
    """Each file's and each crate's outstanding roadmap items.

    Returns ({path: {number: kind}}, {crate: {number: kind}}, rows) where kind
    is "patch" or "feature" and rows maps a number to the roadmap row.
    """
    rows = {row["number"]: row for row in
            roadmap.items(docs.read(os.path.join(root, "ROADMAP.md")))}
    open_items = {n for n, row in rows.items() if row["status"] != "done"}
    patterns = {rel: [mention(k) for k in keys_for(rel, files)] for rel in files}
    sections = audit_sections(docs.read(os.path.join(root, "docs", "AUDIT.md")))

    per_file = {rel: {} for rel in files}

    def attach(target, number, kind):
        if kind == "patch" or number not in target:
            target[number] = kind

    for commit in history["commits"]:
        for number in commit["items"]:
            if number not in open_items:
                continue
            kind = "patch" if commit["kind"] == "fix" else "feature"
            for rel in commit["files"]:
                if rel in per_file:
                    attach(per_file[rel], number, kind)
    for number in sorted(open_items):
        text = rows[number]["item"]
        for rel in files:
            if any(p.search(text) for p in patterns[rel]):
                attach(per_file[rel], number, "feature")
    item_in = {n: re.compile(r"\b[Rr]oadmap (?:item )?%d\b" % n) for n in open_items}
    for section in sections:
        named = [n for n in sorted(open_items) if item_in[n].search(section)]
        if not named:
            continue
        for rel in files:
            if any(p.search(section) for p in patterns[rel]):
                for number in named:
                    attach(per_file[rel], number, "patch")

    per_crate = {}
    for crate, members in crates_of(files):
        mine = {}
        for rel in members:
            for number, kind in per_file[rel].items():
                attach(mine, number, kind)
        words = [mention("fuzz/" if crate == "fuzz" else crate)]
        words += [re.compile(r"\b%s\b" % re.escape(phrase), re.I)
                  for phrase in CRATE_PHRASES.get(crate, ())]
        for number in sorted(open_items):
            if any(word.search(rows[number]["item"]) for word in words):
                attach(mine, number, "feature")
        per_crate[crate] = mine
    return per_file, per_crate, rows


# --- the picture -------------------------------------------------------------

W = 640.0
M = 24.0
SQUARE = 22.0
GAP = 6.0
GUTTER = 118.0
ROW_MIN = 30.0
LINE = 17.0

# The states, in legend order: (name, palette token, hollow, what it means).
# The first, third, fourth and last are the roadmap's own four, in the roadmap's
# own colours; a fix and a planned patch are the two this picture adds.
STATES = [
    ("done", "ok", False, "A feature or other change, landed"),
    ("fixed", "cyan", False, "A fix: a change that names an audit finding"),
    ("next", "accent", False, "On the roadmap and being worked on now"),
    ("planned", "warn", False, "A planned feature, on the roadmap, not started"),
    ("patch", "warn", True, "A planned patch: outstanding work a finding points to"),
    ("blocked", "err", False, "Waiting on something outside the code"),
]
TOKEN = {name: (token, hollow) for name, token, hollow, _ in STATES}

MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep",
          "Oct", "Nov", "Dec")


def day(iso):
    """`2026-09-16` as `16 Sep`, which fits a gutter and reads at a glance."""
    year, month, date = (int(n) for n in iso.split("-"))
    return "%d %s" % (date, MONTHS[month - 1])


def long_day(iso):
    year, month, date = (int(n) for n in iso.split("-"))
    return "%d %s %d" % (date, MONTHS[month - 1], year)


def shorten(text, limit):
    """At most `limit` characters, cut at a word, for a tooltip."""
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(",;:")
    return cut + "..."


def change_square(commit):
    kind = "fixed" if commit["kind"] == "fix" else "done"
    what = "Fix" if kind == "fixed" else "Change"
    refs = ["F-%d" % n for n in commit["findings"]]
    refs += ["roadmap %d" % n for n in commit["items"]]
    label = "%s, %s" % (what, ", ".join(refs)) if refs else what
    return {"state": kind,
            "title": "%s. %s: %s" % (long_day(commit["date"]), label,
                                     shorten(commit["subject"], 170))}


def item_square(number, kind, row):
    status = row["status"]
    if status == "planned" and kind == "patch":
        state = "patch"
    else:
        state = status
    name, detail = roadmap.split_item(row["item"])
    text = roadmap.plain(name or detail)
    what = {"next": "Next", "planned": "Planned", "patch": "Planned patch",
            "blocked": "Blocked"}[state]
    return {"state": state,
            "title": "Roadmap %d. %s: %s" % (number, what, shorten(plainer(text), 170))}


def timeline(history, commits, items, rows):
    """The groups a picture draws: (label, sublabel, hover, squares)."""
    by_release = {}
    for commit in reversed(commits):   # recorded newest first; drawn oldest first
        by_release.setdefault(commit["release"], []).append(commit)
    groups = []
    tags = sorted(history["releases"],
                  key=lambda t: tuple(int(n) for n in VERSION_TAG.match(t).groups()))
    for tag in tags:
        if tag not in by_release:
            continue
        mine = by_release[tag]
        groups.append((tag, day(history["releases"][tag]),
                       "%s, released %s: %d change%s" % (
                           tag, long_day(history["releases"][tag]), len(mine),
                           "" if len(mine) == 1 else "s"),
                       [change_square(c) for c in mine]))
    if "" in by_release:
        mine = by_release[""]
        groups.append(("unreleased", "since %s" % tags[-1] if tags else "",
                       "Landed since the last release: %d change%s" % (
                           len(mine), "" if len(mine) == 1 else "s"),
                       [change_square(c) for c in mine]))
    if items:
        order = {"next": 0, "patch": 1, "planned": 2, "blocked": 3}
        squares = [item_square(n, k, rows[n]) for n, k in items.items()]
        numbered = sorted(zip(items, squares),
                          key=lambda pair: (order[pair[1]["state"]], pair[0]))
        groups.append(("ahead", "ROADMAP.md",
                       "Outstanding roadmap items for this: %d" % len(items),
                       [square for _, square in numbered]))
    return groups


def fits(text, size):
    return len(text) * size * docs.TEXT_RATIO


def drawing(colours, title, what, history, commits, items, rows, kind):
    """One picture: a title, what it does, the timeline and the legend."""
    groups = timeline(history, commits, items, rows)
    per_row = int((W - M * 2 - GUTTER + GAP) // (SQUARE + GAP))
    inner = W - M * 2

    title_size = 14.0
    while title_size > 9 and fits(title, title_size) > inner:
        title_size -= 1
    releases = len([g for g in groups if g[0] not in ("ahead", "unreleased")])
    fixes = sum(1 for c in commits if c["kind"] == "fix")
    since = any(g[0] == "unreleased" for g in groups)
    if not commits:
        summary = "no change recorded through %s; %d item%s ahead" % (
            long_day(history["through"]), len(items), "" if len(items) == 1 else "s")
    else:
        summary = "%d change%s, %d of them fix%s, across %d release%s%s; %d item%s ahead" % (
            len(commits), "" if len(commits) == 1 else "s",
            fixes, "" if fixes == 1 else "es", releases,
            "" if releases == 1 else "s", " and since" if since else "",
            len(items), "" if len(items) == 1 else "s")
    columns = int(inner / (12 * docs.TEXT_RATIO))
    lines = roadmap.wrap(what or "This %s does not describe itself yet: its "
                         "opening comment is where that belongs." % kind, columns)

    y = M + 14
    plan_top = y + 22 + len(lines) * LINE + 22
    plan = []
    at = plan_top
    for group in groups:
        count = len(group[3])
        rows_needed = max(1, (count + per_row - 1) // per_row)
        height = max(ROW_MIN, rows_needed * (SQUARE + GAP) - GAP)
        plan.append((group, at, height))
        at += height + 14
    if not groups:
        at += ROW_MIN
    legend_top = at + 8
    legend_rows = (len(STATES) + 1) // 2
    footer_y = legend_top + legend_rows * 20 + 14
    height = footer_y + 10 + M

    counts = {name: 0 for name, _, _, _ in STATES}
    for group in groups:
        for square in group[3]:
            counts[square["state"]] += 1

    out = []
    add = out.append
    add('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %.0f %.0f" '
        'width="%.0f" height="%.0f" style="max-width:100%%;height:auto" '
        'role="img" aria-label="%s">'
        % (W, height, W, height, docs.esc("%s: %s" % (title, summary))))
