"""A picture of every crate and every source file: what it does, and its timeline.

    python tools/graphs/generate.py              # write the graphs
    python tools/graphs/generate.py --check      # verify they are current
    python tools/graphs/generate.py --record     # re-read the history from git, then write
    python tools/graphs/generate.py --self-test  # prove the reading is right

# What each picture says

One drawing per crate and one per source file, in the same squares, palette and
legend as the roadmap's own picture, so somebody who has read one can read the
other. At the top, what the file is for, in the file's own words: the `//!`
block of a Rust file, the docstring of a Python one, the header comment of
anything else, and a crate's `description` from its `Cargo.toml`. Under that, a
timeline, oldest at the top:

  - one row per release that changed it, and a row for what has landed since
    the last release, with a square for every change: green for a feature or
    any other change, cyan for a fix, which is a change that names a finding;
  - a last row for what is ahead, read from `ROADMAP.md`: blue for an item
    being worked on now, amber for one that is planned, an amber outline for a
    planned patch, and red for one that is blocked.

Every square says what it is when the pointer is over it, through `<title>`,
which every browser shows and every screen reader reads. A square is one
change, not one day and not one size of change: the same rule the roadmap's
picture states under itself, for the same reason.

# Where the history comes from, and why it is a recorded file

The changes are commits, and a commit cannot be read at check time. CI clones
this repository one commit deep, and a generator whose output depends on the
history would also go stale with every commit made, including the commit that
regenerated it. So the history is read once, by `--record`, from a clone that
has all of it and the release tags, into `tools/graphs/history.json`, and every
other run draws from that file. The pictures are then a pure function of the
tree, which is what lets `--check` compare them byte for byte the way every
other generator here is compared.

The recording names the date it reaches, and every picture repeats it, so a
change made after it is missing in a way the picture itself admits. Recording
again is part of cutting a release. It stores no commit hashes: the history may
be rewritten once, to sign it, and a hash is the one thing that would not
survive that.

Renames are followed, so a module that moved crates keeps the history it had
before it moved. A file's history starts where the file was created.

# What is ahead, and what counts as a patch

`ROADMAP.md` is the only place planned work is written down, so it is the only
source here. An outstanding item belongs to a file when its row names the file,
or when a recorded change to the file already names the item; it belongs to a
crate when its row names the crate, or when it belongs to any file in it. It is
a planned **patch** rather than a planned feature when what ties it to the file
is a finding: a fix to the file that names the item, or a write-up in
`docs/AUDIT.md` that names both. Everything else outstanding is a planned
feature, which is what the roadmap mostly holds.

# In plain words

Every part of VeilVoice gets a small picture of its own life: what it is for,
what was added to it and fixed in it in each release, and what is planned for
it next. Point at any square to read what it was.

Pure standard library.
"""

