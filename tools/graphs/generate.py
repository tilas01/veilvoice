def tracked(root):
    out = subprocess.run(
        ["git", "-c", "core.quotePath=false", "ls-files", "-z"], cwd=root,
        stdout=subprocess.PIPE, check=True).stdout.decode("utf-8")
    return [path for path in out.split("\0") if path]


def generated(root, rel):
    """True for a file whose first lines say a generator wrote it."""
    if rel in UNMARKED:
        return True
    try:
        with io.open(os.path.join(root, rel), encoding="utf-8",
                     errors="replace") as handle:
            head = "".join(handle.readline() for _ in range(6))
    except OSError:
        return True
    return "GENERATED" in head


def source_files(root):
    """Every source file git tracks, sorted, generated output excluded."""
    found = []
    for rel in tracked(root):
        if rel.startswith(NOT_SOURCE):
            continue
        name = rel.rsplit("/", 1)[-1]
        if not (name.endswith(SUFFIXES) or name in NAMES):
            continue
        if not os.path.isfile(os.path.join(root, rel)):
            continue  # deleted in the working tree, not yet in the index
        if generated(root, rel):
            continue
        found.append(rel)
    return sorted(found)


