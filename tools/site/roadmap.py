"""The roadmap, as a page anybody can read and a picture of where it has got to.

    python tools/site/roadmap.py           # write the page and the graphic
    python tools/site/roadmap.py --check   # verify they are current

# Why this is generated

`ROADMAP.md` is the file that decides what is done. It is also a two thousand
line document in a repository, which is the wrong shape for the question people
actually ask, which is "is this finished, and if not, what is left".

So this reads that file and writes two things: a picture of every marker
coloured by its state, and a page that puts the picture at the top and the list
under it. Neither is typed. A marker whose status changes in `ROADMAP.md`
changes here on the next run, and `--check` fails the build if it has not, which
is the same arrangement the documentation, the artwork and the search index
already have. A published roadmap that quietly disagrees with the roadmap would
be worse than not publishing one.

# What the picture shows, and what it deliberately does not

One square per marker, in the order the roadmap lists them, grouped by the
section headings that file already has. Colour is state and nothing else:
done, next, planned, blocked.

**Area is not progress.** Every square is the same size, and a marker is not a
day: marker 1 is the entire signal engine and marker 68 is a page of questions.
Reading the coloured fraction as "how far along this is" would be wrong, and the
page says so under the picture rather than leaving somebody to work it out. The
estimates, which are the closest thing to an answer, are in the text where they
can carry the sentence that goes with them.

**Blocked is its own colour, not a shade of unfinished.** Four markers are
blocked on a decision or on somebody else's rules rather than on effort, and
showing them as "not done yet" would promise work that is not going to happen
by working harder.

# In plain words

The roadmap is a long file in the source code. This turns it into a page with a
picture at the top, so somebody can see at a glance what is built and what is
not, without reading two thousand lines or taking anybody's word for it.

The picture is drawn from that file every time, so it cannot say something the
roadmap does not.

Pure standard library.
"""

