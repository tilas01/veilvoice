"""Every command, what it is for, and the same job in the window.

    python tools/docs/commands.py           # write docs/COMMANDS.md
    python tools/docs/commands.py --check   # verify it is current

# The gap this fills

`docs/USER_GUIDE.md` is the long walk through the application, and section 4 of
it shows twelve commands. `veilvoice` has thirty-two. The other twenty were
reachable only by running `--help` and knowing they were there: `sentry`,
`appctl`, `input`, `privilege`, `mandate`, `decoy`, `failsafe`, `volumes`,
`capture`, `import`, `video` and the rest. Every one of them is documented
inside the program, in its own `--help`, and nowhere a reader browsing the
documentation would meet it.

So this is the list, in full, with three things per command that the help text
does not say:

* **what you would actually use it for**, in plain words;
* **where the same job is in the window**, or that there is no such place and
  why, because the two halves of VeilVoice do not match one to one and a reader
  should not have to work out which;
* **one line to copy**, where a command takes arguments worth showing.

# What is derived and what is written

The command list and each command's own one-line summary are read from
`assets/screenshots/cli-help.txt`, which is captured from the program by
`tools/shots/terminal.py` and checked against it in CI. So the *set* of
commands here cannot drift from the program.

The three things above are written, because an explanation is writing. They are
held to the program a different way: a command with nothing written about it
**fails this generator**, and a named window location that is not a tab the
window has fails it too. A command added tomorrow therefore stops a build until
somebody has said what it is for, which is the only arrangement that keeps a
list of thirty-two things honest.

`veilvoice-cli` also checks, in its own test suite, that every subcommand clap
knows about appears in this document, from the other direction: clap's tree
rather than a captured file.

Pure standard library.
"""

