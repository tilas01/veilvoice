def read(relative):
    with io.open(os.path.join(ROOT, relative), encoding="utf-8") as handle:
        return handle.read()


def commands():
    """Every subcommand and its own one-line summary, from the captured help."""
    text = read(HELP).replace("\r\n", "\n")
    try:
        block = text.split("\nCommands:\n", 1)[1].split("\n\nOptions:", 1)[0]
    except IndexError:
        raise SystemExit(
            "%s does not have a `Commands:` block, so the list of commands\n"
            "  cannot be read from it. Re-capture it with\n"
            "      python tools/shots/terminal.py --capture" % HELP)
    found = []
    for line in block.split("\n"):
        match = ROW.match(line)
        if not match:
            continue
        name = match.group("name")
        # `help` is clap's own, printed in the list and absent from the
        # command tree the program is built from, which is what
        # `veilvoice-cli`'s own guard compares the documentation against. A
        # section for it would therefore be a section for a command that
        # does not exist by that guard's reckoning, and the guard is right:
        # there is nothing here to describe that `--help` does not. The
        # introduction says so in a sentence instead.
        if name == "help":
            continue
        found.append((name, match.group("summary").strip()))
    if len(found) < 10:
        raise SystemExit(
            "only %d commands were found in %s, which cannot be right."
            % (len(found), HELP))
    return found


def tabs():
    """Every tab key the window has, so a named location is one that exists."""
    source = read("crates/veilvoice-gui/src/app.rs")
    keys = {m.group("key") for m in TAB_KEY.finditer(source)}
    if not keys:
        raise SystemExit(
            "no tab keys were found in crates/veilvoice-gui/src/app.rs, so a\n"
            "  window location named here cannot be checked against the window.")
    return keys


def checked_notes(found, known_tabs):
    """The notes, with every gap and every wrong tab reported at once."""
    problems = []
    for name, _summary in found:
        note = NOTES.get(name)
        if note is None:
            problems.append(
                "`veilvoice %s` exists and nothing here says what it is for. "
                "Add it to NOTES in tools/docs/commands.py." % name)
            continue
        for field in ("use", "window"):
            if not note.get(field):
                problems.append("`veilvoice %s` has no %s." % (name, field))
        tab, sentence = note.get("window", (None, ""))
        if tab is not None and tab not in known_tabs:
            problems.append(
                "`veilvoice %s` says its place in the window is the %r tab, "
                "and the window has no such tab." % (name, tab))
        if tab is None and not sentence:
            problems.append(
                "`veilvoice %s` has no window equivalent and no reason given. "
                "The reason is the useful half." % name)
    extra = sorted(set(NOTES) - {name for name, _ in found})
    for name in extra:
        problems.append(
            "NOTES describes `veilvoice %s`, which the program does not have. "
            "Either it was renamed or the capture is stale." % name)
    if problems:
        print("docs/COMMANDS.md cannot be written:")
        for problem in problems:
            print("  %s" % problem)
        raise SystemExit(1)
    return NOTES


# Where a tab is, in words a reader can find on screen. Read from the window's
# own tab strip rather than written here: the labels are what a reader sees.
TAB_ROW = re.compile(r'\(Tab::(?P<variant>\w+),\s*"(?P<label>[^"]+)"\)')


def tab_labels():
    source = read("crates/veilvoice-gui/src/app.rs")
    keys = {m.group("variant"): m.group("key") for m in TAB_KEY.finditer(source)}
    out = {}
    for match in TAB_ROW.finditer(source):
        key = keys.get(match.group("variant"))
        if key:
            out[key] = match.group("label")
    return out


def document():
    found = commands()
    known = tabs()
    notes = checked_notes(found, known)
    labels = tab_labels()

    out = [BANNER, ""]
    out.append("# Every command, and the same job in the window")
    out.append("")
    out.append("VeilVoice is two programs over one engine. `veilvoice` is the "
               "command line and `veilvoice-gui` is the window, and they are "
               "not a menu bar and a wrapper around it: each has things the "
               "other does not, for reasons that are given below rather than "
               "left to be discovered.")
    out.append("")
    out.append("This page is the whole of the command line, in the program's "
               "own order, with what each command is for in plain words and "
               "where the same job lives in the window. Every command also "
               "takes `--help`, which is the reference for its flags; this is "
               "the part that says what to reach for. The program's own "
               "`help` command prints those same pages, and is the one entry "
               "in its list with no section below, because there is nothing "
               "to say about it that this sentence has not.")
    out.append("")
    out.append("**Nothing here reaches the network.** The one thing in "
               "VeilVoice that does is the window's check-for-updates button, "
               "and it is not a command.")
    out.append("")
    out.append("## The whole list")
    out.append("")
    out.append("| Command | What it does | In the window |")
    out.append("|---|---|---|")
    for name, summary in found:
        tab, sentence = notes[name]["window"]
        where = "**%s** tab" % labels.get(tab, tab) if tab else "command line only"
        out.append("| [`veilvoice %s`](#veilvoice-%s) | %s | %s |"
                   % (name, name, summary.rstrip("."), where))
    out.append("")
    out.append("---")
    out.append("")

    for name, summary in found:
        note = notes[name]
        tab, sentence = note["window"]
        out.append("## `veilvoice %s`" % name)
        out.append("")
        out.append("> %s" % summary)
        out.append("")
        out.append(note["use"])
        out.append("")
        if tab:
            out.append("**In the window:** %s." % sentence)
        else:
            out.append("**In the window:** nothing, and that is deliberate: "
                       "%s." % sentence)
        out.append("")
        if note.get("example"):
            out.append("```bash")
            out.append(note["example"])
            out.append("```")
            out.append("")

    out.append("---")
    out.append("")
    out.append("## Where to read next")
    out.append("")
    out.append("- [`docs/USER_GUIDE.md`](USER_GUIDE.md) walks through the "
               "window screen by screen and the command line in order.")
    out.append("- [`docs/GUIDE_CLI.md`](GUIDE_CLI.md) is the same guide with "
               "the window's half left out, for somebody at a terminal.")
    out.append("- [`docs/GUIDE_GUI.md`](GUIDE_GUI.md) is the other half.")
    out.append("- [`docs/DEVELOPERS.md`](DEVELOPERS.md) is where the code "
               "that answers each of these commands lives.")
    out.append("")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="verify the document is current, write nothing")
    args = parser.parse_args()

    text = document()
    path = os.path.join(ROOT, OUT)
    if args.check:
        current = read(OUT) if os.path.exists(path) else None
        if current != text:
            print("%s is out of date." % OUT)
            print("  Run: python tools/docs/commands.py")
            return 1
