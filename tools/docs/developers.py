"""The developer's way in: what is where, what is enforced, and where to start.

    python tools/docs/developers.py           # write docs/DEVELOPERS.md
    python tools/docs/developers.py --check   # verify it is current

# What was missing

There is a great deal of documentation about the *program* and, until this,
almost none about the *repository*. `docs/CONTRIBUTING.md` says how to build it
and what a change has to pass. The reference under `website/reference/` and in
the wiki is a page for every crate and every source file, generated from the
doc comments, which is the right place to read about one file and the wrong
place to find out which file to open.

What somebody new needs first is the shape: two binaries over thirteen crates,
which crate answers which question, what the build refuses to let them do, and
where to start reading for the change they came to make. That is this
document, and every list in it is read from the tree rather than typed, so it
describes the repository as it is rather than as it was.

# What is derived

* the crates, their descriptions and their sizes, from the workspace manifest
  and each crate's own `Cargo.toml`;
* the rules a build enforces, from the docstring of each guard in
  `tools/audit/`, so a guard added tomorrow appears here;
* every check and every generator, from `tools/verify.py`'s own lists, which
  is the tool that runs them;
* the tabs and the commands, from the window's tab list and the program's help.

The orientation prose is written, and the files it names are checked to exist.
A recipe that tells somebody to edit a file that has moved is worse than no
recipe, and this repository has published one of those before.

Pure standard library.
"""

