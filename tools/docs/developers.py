# What the doc comments are, and why they are not to be tidied away. This is
# addressed at a reader who is about to reformat a file.
COMMENTS = (
    "**The comments are the documentation, literally.** "
    "`tools/docs/generate.py` reads every `//!` and `///` in the workspace and "
    "writes a page per crate and per file from them, into `docs/files/`, into "
    "the GitHub wiki and into `website/reference/`. A module comment is the "
    "top of a published page; a function comment is an entry on it.\n"
    "\n"
    "So a comment removed is a page that loses a paragraph, and a comment "
    "rewritten to be shorter is a page that says less. The ratio of comment "
    "to code here is deliberately high and is not a defect to be cleaned up. "
    "Where a comment explains *why* a number is what it is, or why an obvious "
    "alternative was refused, it is usually recording a defect that was found "
    "the hard way and is written up in `docs/AUDIT.md` under a finding number.\n"
    "\n"
    "Add to them rather than replacing them. If a comment has become wrong, "
    "the fix is to say what is true now, in the same detail, in the same "
    "commit as the change that made it wrong.")


def read(relative):
    with io.open(os.path.join(ROOT, relative), encoding="utf-8") as handle:
        return handle.read()


def guards():
    """Every guard in `tools/audit/`, with the line it introduces itself by."""
    folder = os.path.join(ROOT, "tools", "audit")
    out = []
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".py") or name.startswith("_"):
            continue
        text = read("tools/audit/%s" % name)
        match = re.search(r'^"""(.+?)(?:\n|""")', text, re.M | re.S)
        first = match.group(1).strip() if match else ""
        if not first:
            raise SystemExit(
                "tools/audit/%s has no docstring, so there is nothing to say\n"
                "  about what it enforces. Every guard in this repository "
                "explains itself\n  on its first line." % name)
        out.append(("tools/audit/%s" % name, first))
    if len(out) < 5:
        raise SystemExit("only %d guards were found, which cannot be right"
                         % len(out))
    return out


def crate_rows():
    """Every crate, its description and its size, from the workspace itself."""
    lines = docs.functional_lines_by_crate()
    rows = []
    for crate in docs.workspace_crates(ROOT):
        description = docs.crate_description(ROOT, crate) or ""
        count = lines.get(crate)
        rows.append((crate, description, count))
    return rows


def missing_paths():
    """Any file this document tells somebody to open that is not there."""
    wanted = []
    for _title, paths, _note in STARTING_POINTS:
        wanted.extend(paths)
    return [path for path in wanted
            if not os.path.exists(os.path.join(ROOT, path))]


def steps(argv):
    """A command from `tools/verify.py`'s lists, as a reader would type it."""
    out = []
    for part in argv:
        out.append("python" if part == sys.executable else part)
    return " ".join(out)


def document():
    gone = missing_paths()
    if gone:
        raise SystemExit(
            "docs/DEVELOPERS.md sends a reader to files that do not exist:\n"
            "  %s\n"
            "  Fix STARTING_POINTS in tools/docs/developers.py."
            % "\n  ".join(gone))

