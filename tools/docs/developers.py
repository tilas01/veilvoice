    out.append("")
    out.append("The same crates, drawn as a graph of what calls what, are on "
               "each crate's page in the reference. Those pages are generated "
               "from the doc comments, so they are as current as the code.")
    out.append("")

    out.append("## Where to start, by what you came to change")
    out.append("")
