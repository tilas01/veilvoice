"""Pictures of the command line, drawn from its real output.

    python tools/shots/terminal.py --capture   # run the commands, save the text
    python tools/shots/terminal.py             # draw the SVGs from that text
    python tools/shots/terminal.py --check     # verify the SVGs match the text
    python tools/shots/terminal.py --self-test # prove the build check catches it

# Two steps, on purpose

`--capture` runs `veilvoice` and writes what it printed into
`assets/screenshots/cli-<name>.txt`. That step needs a build, a machine, and a
person deciding the output is right; it is not something CI can do.

Everything after that is a pure function of those text files, so the drawings
**are** reproducible and CI checks them exactly the way it checks the banners:
regenerate into memory, compare, fail on a difference. A picture of a command
line that disagrees with the command line is documentation that lies, and this
is the arrangement that makes that impossible to commit by accident.

The text is committed beside the picture and is the thing to read in a diff. An
SVG diff is unreadable; a diff of what the program printed is the review.

# Why SVG and not a screenshot

The same reason the website's banner is text: it follows a palette rather than
being baked in one, it can be selected, searched and read aloud, and it stays
sharp at any size. Finding F-37 was this project's own claims rendered
illegibly inside an image. Claims stay out of images.

# What is captured, and what is deliberately not

Only commands that print the program's own help and its own findings. Nothing
that names this machine's devices, users or paths: a demonstration picture is
published, and a device list is a description of somebody's hardware.

Pure standard library.
"""

